export function getRiskCopy(score: number) {
  if (score >= 70) return { label: UI_COPY.risk.critical, icon: "critical" as const };
  if (score >= 45) return { label: UI_COPY.risk.high, icon: "high" as const };
  if (score >= 25) return { label: UI_COPY.risk.medium, icon: "medium" as const };
  return { label: UI_COPY.risk.low, icon: "low" as const };
}
